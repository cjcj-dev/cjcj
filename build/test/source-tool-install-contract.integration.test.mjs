#!/usr/bin/env zx
// Full native SDK input is supplied by the production job. Missing inputs fail;
// the ordinary Node suite exercises source-tool-install-interface.test.mjs.
import fs from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {buildConfig} from '../lib/config.mjs';
import * as packageStage from '../srcbuild/stages/package.mjs';
import {fileDigest} from '../../ci/bootstrap/sdk-flow.mjs';
import {sdkEnvironment} from '../../ci/bootstrap/sdk-platform.mjs';
const parent=process.env.RELEASE_EVIDENCE_TEST_ROOT;
const source=process.env.CJCJ_SRCBUILD_CONSUMER_SDK;
const workspaceInput=process.env.CANGJIE_WORKSPACE;
const official=process.env.CJCJ_OFFICIAL_SDK_ROOT||process.env.CJCJ_SRCBUILD_HOST_SDK;
if(!parent||!source||!workspaceInput||!official)throw new Error('SOURCE_TOOL_SDK_INPUT_REQUIRED: RELEASE_EVIDENCE_TEST_ROOT, CJCJ_SRCBUILD_CONSUMER_SDK, CANGJIE_WORKSPACE, official SDK');
const targetKey=process.env.CJCJ_SRCBUILD_TARGET||'linux-x64';
if(targetKey!=='linux-x64')throw new Error('SOURCE_TOOL_SDK_NATIVE_LINUX_REQUIRED');
await fs.mkdir(parent,{recursive:true});
test('A8 real SDK tools survive same-directory packaging and explicit unpack consumption',async()=>{
 const work=await fs.mkdtemp(path.join(parent,'a8-real-sdk-')),workspace=path.join(work,'workspace');
 const config=buildConfig({workspace,buildRoot:path.join(work,'buildtools'),targetKey,
  cangjieVersion:process.env.SOURCE_SDK_VERSION||'0.0.2-dev',
  consumerSdk:path.join(workspace,'software/cangjie'),officialSdkRoot:official});
 const sdk=config.consumerSdk;
 // Copy the production installation as an entity; never install fixture tools.
 await fs.mkdir(path.dirname(sdk),{recursive:true});
 await fs.cp(source,sdk,{recursive:true,dereference:false,verbatimSymlinks:true});
 const stdx=path.join('cangjie_stdx','target',config.target.stdxTargetSubdir());
 await fs.mkdir(path.dirname(path.join(workspace,stdx)),{recursive:true});
 await fs.cp(path.join(workspaceInput,stdx),path.join(workspace,stdx),{recursive:true,dereference:false,verbatimSymlinks:true});
 const tools=JSON.parse(await fs.readFile(path.join(sdk,'TOOLS-INPUTS.json'),'utf8'));
 const before={};
 for(const name of ['cjpm','cjfmt','hle','LSPServer','cjcov','cjtrace-recover','cjlint','cjprof','cjcompat']){
  const rel='tools/bin/'+name,retained=path.join(sdk,'.target-tools',rel);
  assert.equal(await fileDigest(retained),tools.files[rel].sha256,rel+' native output');
  before[rel]=await fs.readFile(path.join(sdk,rel));
 }
 // Includes packageStage.run -> packageInstall -> both installed and unpacked
 // verifyInstall calls. The production ABI/parity/ordinary/macro gates stay real.
 const archives=await packageStage.run(config);
 const unpack=path.join(work,'unpacked');await fs.mkdir(unpack);
 const tar=spawnSync('tar',['-xzf',archives[0],'-C',unpack],{encoding:'utf8'});
 assert.equal(tar.status,0,tar.stderr);
 const relocated=path.join(unpack,'cangjie');
 for(const [rel,bytes]of Object.entries(before))assert.deepEqual(await fs.readFile(path.join(relocated,rel)),bytes,'package keeps actual installed launcher '+rel);
 // Real cjcov consumes coverage generated by the relocated compiler/program.
 const coverage=path.join(work,'coverage');await fs.mkdir(coverage);
 const input=path.join(coverage,'main.cj'),binary=path.join(coverage,'main');
 await fs.writeFile(input,'main() { println("SDK coverage consumer") }\n');
 const env=sdkEnvironment(relocated,'linux_x86_64');delete env.LD_PRELOAD;delete env.LD_AUDIT;
 const records=[];
 for(const argv of [[path.join(relocated,'bin/cjc'),'--coverage',input,'-o',binary],[binary],
  [path.join(relocated,'tools/bin/cjcov'),'-o',path.join(coverage,'report'),'--html-details']]){
  const result=spawnSync(argv[0],argv.slice(1),{cwd:coverage,env,encoding:'utf8'});
  records.push({argv,rc:result.status,signal:result.signal,stdout:result.stdout,stderr:result.stderr});
  await fs.writeFile(path.join(work,'consumers.json'),JSON.stringify(records,null,2)+'\n');
  assert.equal(result.status,0,result.stderr||result.error?.message);
 }
 assert.match(records[1].stdout,/SDK coverage consumer/);
 const report=await fs.readFile(path.join(coverage,'report/index.html'),'utf8');
 assert.match(report,/main\.cj/);
 console.log('A8_PACKAGE_TARGET_ASSERTION_REACHED',JSON.stringify({preserved:true,archives,relocated,tools:Object.keys(before)}));
});
