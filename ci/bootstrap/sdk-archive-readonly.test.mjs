import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const parent=process.env.SDK_FLOW_TEST_ROOT||(process.env.RELEASE_EVIDENCE_TEST_ROOT&&path.join(process.env.RELEASE_EVIDENCE_TEST_ROOT,'sdk-archive-readonly'));
if(!parent)throw Error('SDK_FLOW_TEST_ROOT or RELEASE_EVIDENCE_TEST_ROOT required');
await fs.mkdir(parent,{recursive:true});
for(const readOnlySource of [false,true])test(`archive CLI readOnlySource=${readOnlySource} preserves source and exercises relocation`,async()=>{
 const root=await fs.mkdtemp(path.join(parent,'archive-')),install=path.join(root,'sdk'),archive=path.join(root,'sdk.tar.gz');
 await fs.mkdir(install);await fs.writeFile(path.join(install,'payload'),'installed');
 const initial=await fs.stat(install,{bigint:true});
 const check=path.join(root,'check.mjs');
 await fs.writeFile(check,`import fs from 'node:fs';import assert from 'node:assert/strict';assert.equal(fs.existsSync(process.argv[2]),${readOnlySource});assert.equal(fs.readFileSync(process.argv[3]+'/payload','utf8'),'installed');console.log('ARCHIVE_SOURCE_MODE_ASSERT_REACHED');if(process.env.REJECT_ARCHIVE)process.exit(19);`);
 const input={install,archive,readOnlySource,test:{commands:[{argv:[process.execPath,check,install,'\${install}']}]}};
 const request=path.join(root,'request.json');await fs.writeFile(request,JSON.stringify(input));
 const cli=fileURLToPath(new URL('./sdk-build.mjs',import.meta.url));
 const run=()=>spawnSync(process.execPath,[cli,'--archive-inputs',request],{encoding:'utf8'});
 let r=run();assert.equal(r.status,0,r.stderr);assert.match(r.stdout,/ARCHIVE_SOURCE_MODE_ASSERT_REACHED/);
 const first=await fs.readFile(archive);assert.equal(await fs.readFile(archive+'.unpacked/sdk/payload','utf8'),'installed');
 input.test.commands[0].env={REJECT_ARCHIVE:'1'};await fs.writeFile(request,JSON.stringify(input));
 r=run();assert.equal(r.status,19,r.stderr);assert.match(r.stdout,/ARCHIVE_SOURCE_MODE_ASSERT_REACHED/);
 assert((await fs.readFile(archive)).equals(first));assert.equal(await fs.readFile(install+'/payload','utf8'),'installed');
 const after=await fs.stat(install,{bigint:true});assert.equal(after.ino,initial.ino);
 if(readOnlySource)assert.equal(after.ctimeNs,initial.ctimeNs,'read-only source was not renamed');
 const bad=spawnSync(process.execPath,[cli,'--archive-inputs',request,'--no-package'],{encoding:'utf8'});
 assert.equal(bad.status,1);assert.match(bad.stderr,/ARCHIVE_ARGUMENT_CONFLICT/);
 console.log('ARCHIVE_REJECTION_PRESERVED_SOURCE_AND_PRIOR_PACKAGE');
});
