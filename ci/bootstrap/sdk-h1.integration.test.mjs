// Finite public native H1 regression; no SDK qualification.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const parent=process.env.SDK_H1_TEST_ROOT;
assert(parent,'SDK_H1_TEST_ROOT required');
const stage=path.resolve('ci/bootstrap/sdk-native-stage.mjs');
test('public Linux H1 uses normal cjpm, host domain and restores temporary source edits',()=>{
 fs.mkdirSync(parent,{recursive:true});const root=fs.mkdtempSync(path.join(parent,'h1-'));
 const write=(file,text)=>{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);};
 const run=(name,argv,env=process.env)=>{
  const result=spawnSync(argv[0],argv.slice(1),{env,encoding:'utf8'});
  write(root+'/'+name+'.stdout',result.stdout||'');write(root+'/'+name+'.stderr',result.stderr||'');
  write(root+'/'+name+'.json',JSON.stringify({argv,rc:result.status,signal:result.signal}));return result;
 };
 const ok=(name,argv)=>{const r=run(name,argv);assert.equal(r.status,0,r.stdout+r.stderr);return r.stdout.trim();};
 const commit=(dir,name)=>{ok(name+'-init',['git','init','-q',dir]);ok(name+'-add',['git','-C',dir,'add','.']);
  ok(name+'-commit',['git','-C',dir,'-c','user.name=Zxilly','-c','user.email=zxilly@outlook.com','commit','-qm','Finite H1 CLI regression']);
  return ok(name+'-head',['git','-C',dir,'rev-parse','HEAD']);};
 const source=root+'/source',host=root+'/host',sdk=root+'/native';
 const before='[package]\ncompile-option = "-O0"\n';write(source+'/cjpm.toml',before);
 const lockBefore='version = 0\n\n[requires]\n';write(source+'/cjpm.lock',lockBefore);
 write(source+'/runtime_shim/cjc_runtime_config.c','const char* commit=CJCJ_COMMIT;\n');
 write(source+'/runtime_shim/cjc_heap_defaults.c','const int heap_defaults=4;\n');
 const sourceCommit=commit(source,'source');
 write(host+'/tools/bin/cjpm',`#!/usr/bin/env node
const fs=require('fs'),path=require('path'),e=process.env;
const source=process.cwd(),release=path.join(source,'target/release');
console.log('H1_CJPM_PRODUCER_REACHED');
fs.writeFileSync('cjpm.lock','version = 1\\n\\n[requires]\\n');
if(e.H1_FIXTURE_FAIL==='1')process.exit(17);
fs.mkdirSync(path.join(release,'bin'),{recursive:true});
fs.writeFileSync(path.join(release,'bin/cjc@cjcj'),'finite product, not a compiler');
fs.writeFileSync(path.join(release,'contract.json'),JSON.stringify({env:e,argv:process.argv.slice(2),manifest:fs.readFileSync('cjpm.toml','utf8'),shim:fs.readFileSync('runtime_shim/cjselfhost_llvmshim.o','utf8'),configurationObject:fs.statSync('runtime_shim/cjc_runtime_config.o').size,heapDefaultsObject:fs.statSync('runtime_shim/cjc_heap_defaults.o').size}));
`);
 fs.chmodSync(host+'/tools/bin/cjpm',0o755);
 write(root+'/native-cc',`#!/usr/bin/env node
const {spawnSync}=require('node:child_process');
if(process.env.LD_LIBRARY_PATH||process.env.LD_PRELOAD||process.env.LD_AUDIT)throw Error('H1_NATIVE_CC_LOADER_DOMAIN');
console.log('H1_NATIVE_CC_DOMAIN_REACHED');
const r=spawnSync('cc',process.argv.slice(2),{stdio:'inherit'});process.exit(r.status??1);
`);
 fs.chmodSync(root+'/native-cc',0o755);
 const object='third_party/llvm/fixed-llc/cjselfhost_llvmshim.o',bytes='finite selected N shim';write(sdk+'/'+object,bytes);
 const hash=text=>createHash('sha256').update(text).digest('hex');
 const nativeShim={source:{commit:sourceCommit},compiler:{commit:'a'.repeat(40)},llvm:{commit:'b'.repeat(40)},object:{path:object,bytes:Buffer.byteLength(bytes),sha256:hash(bytes)}};
 write(sdk+'/BUILD-INPUTS.json',JSON.stringify({commits:{shim:sourceCommit,compiler:'a'.repeat(40),llvm:'b'.repeat(40)},nativeShim}));
 const argv=output=>[process.execPath,stage,'--kind','h1','--source',source,'--commit',sourceCommit,'--sdk',sdk,'--runtime',root+'/runtime','--host',host,'--output',output,'--platform','linux_x86_64','--jobs','1','--heap','1GB','--cc',root+'/native-cc'];
 const output=root+'/output',r=run('h1',argv(output));assert.equal(r.status,0,r.stdout+r.stderr);
 assert.match(r.stdout,/H1_NATIVE_CC_DOMAIN_REACHED/);
 const contract=JSON.parse(fs.readFileSync(output+'.h1/out/release/contract.json'));
 assert.equal(contract.env.CANGJIE_HOME,host,'H1_MUST_EXECUTE_IN_HOST_DOMAIN');
 assert.ok(contract.env.PATH.startsWith(host+'/bin:'+host+'/tools/bin:'+host+'/third_party/llvm/bin:'));
 assert.ok(contract.env.LD_LIBRARY_PATH.startsWith(host+'/runtime/lib/linux_x86_64_cjnative:'));
 assert.equal(contract.env.CANGJIE_BUILD_JOBS,'1');assert.equal(contract.env.CJCJ_COMMIT,sourceCommit);
 assert.equal(contract.env.SB_SOURCE,undefined);assert.deepEqual(contract.argv,['build','-j1']);
 console.log('H1_O1_TRIMPATH_ASSERTION_REACHED');
 assert.equal(contract.manifest,'[package]\ncompile-option = '+JSON.stringify('-O1 --trimpath '+source)+'\n','H1_O1_TRIMPATH_REQUIRED');
 assert.ok(contract.configurationObject>0);assert.ok(contract.heapDefaultsObject>0);assert.equal(contract.shim,bytes,'H1_MUST_CONSUME_SELECTED_NATIVE_SHIM');
 assert.deepEqual(JSON.parse(fs.readFileSync(output+'.h1/parameters.json')),{compile_flags:''});
 assert.equal(fs.readFileSync(output+'.h1/out/release/bin/cjc@cjcj','utf8'),'finite product, not a compiler');
 assert.equal(fs.readFileSync(output+'/bin/cjcj-stage1','utf8'),'finite product, not a compiler');
 assert.equal(fs.existsSync(output+'/bin/release'),false);assert.equal(fs.readFileSync(source+'/cjpm.toml','utf8'),before);
 assert.equal(fs.readFileSync(source+'/cjpm.lock','utf8'),lockBefore,'H1_LOCK_MUST_RESTORE_AFTER_SUCCESS');
 const commands=JSON.parse(fs.readFileSync(output+'.commands.json'));assert.equal(commands.length,3);assert.ok(commands.every(row=>row.rc===0));
 assert.ok(commands[0].argv.includes('-DCJCJ_COMMIT=\"'+sourceCommit+'\"'));
 assert.ok(commands[1].argv.includes(source+'/runtime_shim/cjc_heap_defaults.c'));
 assert.deepEqual(commands[2].argv,[host+'/tools/bin/cjpm','build','-j1']);
 const facts=JSON.parse(fs.readFileSync(output+'/bin/build-inputs.json'));assert.equal(facts.source,sourceCommit);assert.equal(facts.sourceRoot,source);assert.equal(facts.native,sdk);assert.equal(facts.host,host);assert.deepEqual(facts.nativeShim,nativeShim);assert.equal(facts.sha256,hash('finite product, not a compiler'));
 assert.equal(facts.sourceChanges['cjpm.toml'].beforeSha256,hash(before));
 const failed=run('h1-failed',argv(root+'/failed'),{...process.env,H1_FIXTURE_FAIL:'1'});
 assert.equal(failed.status,17,failed.stdout+failed.stderr);assert.match(failed.stdout,/H1_CJPM_PRODUCER_REACHED/);
 assert.equal(fs.readFileSync(source+'/cjpm.toml','utf8'),before,'H1_SOURCE_MUST_RESTORE_AFTER_FAILURE');
 assert.equal(fs.readFileSync(source+'/cjpm.lock','utf8'),lockBefore,'H1_LOCK_MUST_RESTORE_AFTER_FAILURE');
 assert.equal(JSON.parse(fs.readFileSync(root+'/failed.commands.json'))[1].rc,17);
 console.log('H1_PUBLIC_CJPM_CONTRACT_AND_RESTORATION_REACHED');
});
